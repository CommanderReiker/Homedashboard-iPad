// Deterministic single-file HACS distribution, no third-party build dependencies.
import {readFile, writeFile, mkdir} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=(p)=>readFile(path.join(root,p),'utf8');
const {version}=JSON.parse(await read('package.json'));
const data=await read('www/home-dashboard/data.js');
const source=await read('www/home-dashboard/home-dashboard.js');
if(!source.includes(`const VERSION='${version}';`))throw new Error('Source version must match package.json');
const importLine=source.split('\n')[0];
if(!/^import \{.*\} from '\.\/data\.js\?v=[\d.]+';$/.test(importLine))throw new Error('Unexpected imports; review bundling');
const code=source.slice(importLine.length).replace(/^export /gm,'');
const helpers=data.replace(/^export /gm,'');
if(/^\s*(import|export)\b/m.test(code+helpers))throw new Error('Bundle still has external imports/exports');
const artifact=`/* Home Dashboard iPad v${version} | Generated by npm run build. Edit sources, not this file. */\n(()=>{\n'use strict';\n${helpers}\nconst esc=escapeHTML;\n${code}\n})();\n`;
const output='dist/Homedashboard-iPad.js';
if(process.argv.includes('--check')){
  if(await read(output)!==artifact)throw new Error('Stale dist artifact: run npm run build');
  console.log(`Distribution matches sources (v${version}).`);
}else{
  await mkdir(path.join(root,'dist'),{recursive:true});
  await writeFile(path.join(root,output),artifact);console.log(`Built ${output} (v${version}).`);
}
